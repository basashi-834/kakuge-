float PixelTextWidth(const std::string& text, float dot) {
    int glyphs = 0;
    for (size_t i = 0; i < text.size();) {
        int len = Utf8SequenceLength(static_cast<unsigned char>(text[i]));
        i += static_cast<size_t>(len);
        glyphs++;
    }
    if (glyphs == 0) return 0.0f;
    // 最後の文字のうしろの隙間は幅に含めません。
    return (glyphs * kGlyphAdvanceCols - 1) * dot;
}

void DrawPixelText(Renderer& r, const std::string& text, float x, float y, float dot, Color color) {
    if (color.a == 0) return;
    float cursorX = x;
    for (size_t i = 0; i < text.size();) {
        unsigned char lead = static_cast<unsigned char>(text[i]);
        int len = Utf8SequenceLength(lead);
        if (len == 1) {
            if (const char* const* rows = FindGlyph(text[i])) {
                // 点をひとつずつ四角形として描きます。
                // 横に連続する点はまとめて 1 本の長い四角形にすると
                // 描画の回数が減って速くなるので、そうしています。
                for (int row = 0; row < kGlyphRows; ++row) {
                    const char* line = rows[row];
                    int col = 0;
                    while (col < kGlyphCols) {
                        if (line[col] != '#') { col++; continue; }
                        int runStart = col;
                        while (col < kGlyphCols && line[col] == '#') col++;
                        int runLen = col - runStart;
                        r.FillRect(cursorX + runStart * dot, y + row * dot,
                                   runLen * dot, dot, color);
                    }
                }
            }
        }
        // 対応していない文字（日本語など）も、幅だけは進めます。
        cursorX += kGlyphAdvanceCols * dot;
        i += static_cast<size_t>(len);
    }
}

void DrawPixelTextCentered(Renderer& r, const std::string& text,
                           float x, float y, float w, float h, float dot, Color color) {
    float textW = PixelTextWidth(text, dot);
    float textH = kGlyphRows * dot;
    DrawPixelText(r, text, x + (w - textW) / 2.0f, y + (h - textH) / 2.0f, dot, color);
}

void DrawPixelTextRight(Renderer& r, const std::string& text, float rightX, float y,
                        float dot, Color color) {
    DrawPixelText(r, text, rightX - PixelTextWidth(text, dot), y, dot, color);
}

