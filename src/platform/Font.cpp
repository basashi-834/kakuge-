bool Contains(const std::uint32_t* list, size_t count, std::uint32_t v) {
    for (size_t i = 0; i < count; ++i) {
        if (list[i] == v) return true;
    }
    return false;
}

// ---------------------------------------------------------------------
// パソコンの日本語フォント
// ---------------------------------------------------------------------
// 日本語を描く大きさ（ピクセル）。
//
// 12 という数字は「漢字が読める最小」と「画面に収まる最大」の
// ちょうど境目です。11 以下だと「発」「直」のような画数の多い字が
// つぶれて読めません。13 以上にすると、384px 幅の画面に項目名と
// 数値を 1 行で並べられなくなります。
constexpr int kJpPixelSize = 12;

TrueTypeFont& JpFont() {
    static TrueTypeFont font;
    return font;
}

// ベースライン（文字が並ぶ下の線）を、行の上端から何ピクセル下に置くか。
// 漢字の上端がちょうど行の上端に来るように決めます。こうすると
// 英数字（5x7）と日本語の「上端」がそろい、混ざった行がガタつきません。
int JpBaseline() {
    int ascent = JpFont().Ascent(kJpPixelSize);
    return ascent > 1 ? ascent - 1 : ascent;
}

const char* const* FindGlyph(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 32); // 小文字→大文字
    for (const auto& entry : kGlyphTable) {
        if (entry.ch == c) return entry.rows;
    }
    return nullptr; // 対応していない文字
}

const char* const* FindKanaGlyph(std::uint32_t cp) {
    for (const auto& entry : kKanaTable) {
        if (entry.cp == cp) return entry.rows;
    }
    return nullptr;
}

// UTF-8 の 1 文字が何バイトぶんか。
int Utf8SequenceLength(unsigned char lead) {
    if (lead < 0x80) return 1;
    if ((lead & 0xE0) == 0xC0) return 2;
    if ((lead & 0xF0) == 0xE0) return 3;
    if ((lead & 0xF8) == 0xF0) return 4;
    return 1; // 壊れたバイトは 1 バイトとして飛ばす
}

// UTF-8 の 1 文字を読み取って、文字コードと使ったバイト数を返す。
std::uint32_t Utf8Decode(const std::string& text, size_t index, int& lengthOut) {
    unsigned char lead = static_cast<unsigned char>(text[index]);
    int len = Utf8SequenceLength(lead);
    // 文字列の途中で切れている場合は 1 バイトとして扱い、無限ループを防ぐ。
    if (index + static_cast<size_t>(len) > text.size()) { lengthOut = 1; return lead; }
    lengthOut = len;
    if (len == 1) return lead;

    std::uint32_t cp = lead & (0xFF >> (len + 1));
    for (int i = 1; i < len; ++i) {
        unsigned char b = static_cast<unsigned char>(text[index + static_cast<size_t>(i)]);
        if ((b & 0xC0) != 0x80) { lengthOut = 1; return lead; } // 壊れている
        cp = (cp << 6) | (b & 0x3F);
    }
    return cp;
}

// 1 文字を「描くもの」に翻訳した結果。
//
// 濁点つきの字は 2 つのグリフ（素の字＋点）になるので、
// 描く側が 1 文字＝1 グリフだと思い込まないよう、ここで束にして返します。
struct ResolvedChar {
    // 内蔵のドット表を使う場合
    const char* const* rows[2] = {nullptr, nullptr}; // 描くグリフ（最大 2 つ）
    int cols[2] = {0, 0};                            // それぞれの横のドット数
    // パソコンのフォントを使う場合（こちらが入っていれば優先）
    const TrueTypeFont::Glyph* ttf[2] = {nullptr, nullptr};
    int advance[2] = {0, 0};                         // それぞれの送り幅
    int count = 0;
};

void PushGlyph(ResolvedChar& out, const char* const* rows, int cols, int advance) {
    if (out.count >= 2) return;
    out.rows[out.count] = rows;
    out.cols[out.count] = cols;
    out.ttf[out.count] = nullptr;
    out.advance[out.count] = advance;
    out.count++;
}

void PushTtfGlyph(ResolvedChar& out, const TrueTypeFont::Glyph* g, int advance) {
    if (out.count >= 2) return;
    out.rows[out.count] = nullptr;
    out.cols[out.count] = 0;
    out.ttf[out.count] = g;
    out.advance[out.count] = advance;
    out.count++;
}

ResolvedChar ResolveChar(std::uint32_t cp) {
    ResolvedChar out;

    // 半角の英数字・記号
    if (cp < 0x80) {
        PushGlyph(out, FindGlyph(static_cast<char>(cp)), kGlyphCols, kGlyphAdvanceCols);
        return out;
    }

    // パソコンの日本語フォントが読めていれば、そちらで描きます。
    // 漢字もひらがなも、置き換えなしでそのまま出せます。
    if (JpFont().IsLoaded()) {
        if (const TrueTypeFont::Glyph* g = JpFont().GetGlyph(cp, kJpPixelSize)) {
            // 送り幅はフォントが持っている値に 1 ドットの隙間を足します。
            // 隙間が無いと、隣り合う漢字がくっついて 1 文字に見えます。
            int advance = g->advance > 0 ? g->advance + 1 : kJpPixelSize + 1;
            PushTtfGlyph(out, g, advance);
            return out;
        }
        // このフォントに無い文字は、下の内蔵カナに任せます。
    }

    // ---- ここから下は内蔵のカナ（フォントが読めない環境用）----
    // ひらがな（U+3041-U+3096）はカタカナに置き換える。
    if (cp >= 0x3041 && cp <= 0x3096) cp += 0x60;

    // 濁点・半濁点そのものは、幅を詰めて描きます。
    if (cp == kCpDakuten || cp == kCpHandakuten) {
        PushGlyph(out, FindKanaGlyph(cp), kKanaCols, kMarkAdvanceCols);
        return out;
    }

    if (const char* const* rows = FindKanaGlyph(cp)) {
        PushGlyph(out, rows, kKanaCols, kKanaAdvanceCols);
        return out;
    }

    // 表に無い場合は、濁点つきの字かどうかを調べて分解する。
    std::uint32_t base = 0, mark = 0;
    if (cp == kCpKatakanaVu) {
        base = kCpKatakanaU; mark = kCpDakuten;                 // ヴ → ウ ＋ ゛
    } else if (Contains(kDakutenBases, std::size(kDakutenBases), cp - 1)) {
        base = cp - 1; mark = kCpDakuten;                       // ガ → カ ＋ ゛
    } else if (Contains(kHandakutenBases, std::size(kHandakutenBases), cp - 2)) {
        base = cp - 2; mark = kCpHandakuten;                    // パ → ハ ＋ ゜
    }
    if (base != 0) {
        PushGlyph(out, FindKanaGlyph(base), kKanaCols, kKanaAdvanceCols);
        PushGlyph(out, FindKanaGlyph(mark), kKanaCols, kMarkAdvanceCols);
        return out;
    }

    // それでも分からない文字（漢字など）は、全角ぶんの幅だけ空けます。
    // 何も描かないのは、豆腐（□）を出すより読みやすいという判断です。
    PushGlyph(out, nullptr, kKanaCols, kKanaAdvanceCols);
    return out;
}

