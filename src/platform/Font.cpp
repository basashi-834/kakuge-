bool InitJapaneseFont(const std::string& dataDir) {
    namespace fs = std::filesystem;
    // data フォルダに置かれたフォントを最優先で探します。
    // 好きな書体に差し替えたいときは、ここに置くだけで済みます。
    std::string preferred;
    for (const char* name : {"font.ttf", "font.ttc", "font.otf"}) {
        std::error_code ec;
        fs::path candidate = fs::path(dataDir) / name;
        if (fs::exists(candidate, ec)) { preferred = candidate.string(); break; }
    }
    return LoadSystemJapaneseFont(JpFont(), preferred);
}

std::string JapaneseFontPath() {
    return JpFont().IsLoaded() ? JpFont().Path() : std::string();
}

int JapaneseLineHeight() {
    // 内蔵のカナは 8 ドット。パソコンのフォントを使うときは、
    // ベースラインの下（はらい）まで含めた高さにします。
    if (!JpFont().IsLoaded()) return 8;
    return JpBaseline() + 2;
}

float PixelTextWidth(const std::string& text, float dot) {
    int cols = 0;
    for (size_t i = 0; i < text.size();) {
        int len = 0;
        ResolvedChar rc = ResolveChar(Utf8Decode(text, i, len));
        for (int g = 0; g < rc.count; ++g) cols += rc.advance[g];
        i += static_cast<size_t>(len);
    }
    if (cols == 0) return 0.0f;
    // 最後の文字のうしろの隙間は幅に含めません。
    return (cols - 1) * dot;
}

void DrawPixelText(Renderer& r, const std::string& text, float x, float y, float dot, Color color) {
    if (color.a == 0) return;
    float cursorX = x;
    for (size_t i = 0; i < text.size();) {
        int len = 0;
        ResolvedChar rc = ResolveChar(Utf8Decode(text, i, len));
        i += static_cast<size_t>(len);

        for (int g = 0; g < rc.count; ++g) {
            // ---- パソコンのフォントで描く場合 ----
            if (const TrueTypeFont::Glyph* tg = rc.ttf[g]; tg != nullptr) {
                // bearingY は「ベースラインから字の上端までの高さ」なので、
                // 上端の位置は「行の上端 ＋ ベースライン － bearingY」です。
                float gx = cursorX + tg->bearingX * dot;
                float gy = y + (JpBaseline() - tg->bearingY) * dot;
                for (int row = 0; row < tg->height; ++row) {
                    int col = 0;
                    while (col < tg->width) {
                        if (!tg->Get(col, row)) { col++; continue; }
                        int runStart = col;
                        while (col < tg->width && tg->Get(col, row)) col++;
                        r.FillRect(gx + runStart * dot, gy + row * dot,
                                   (col - runStart) * dot, dot, color);
                    }
                }
                cursorX += rc.advance[g] * dot;
                continue;
            }

            const char* const* rows = rc.rows[g];
            if (rows != nullptr) {
                // 点をひとつずつ四角形として描きます。
                // 横に連続する点はまとめて 1 本の長い四角形にすると
                // 描画の回数が減って速くなるので、そうしています。
                //
                // 縦のドット数は「行の文字列が終わるまで」ではなく、
                // 英数字なら 7、カナなら 8 と決まっています。
                // 横のドット数（cols）から、どちらの表の字かが分かります。
                int rowCount = (rc.cols[g] == kKanaCols) ? kKanaRows : kGlyphRows;
                for (int row = 0; row < rowCount; ++row) {
                    const char* line = rows[row];
                    int col = 0;
                    while (col < rc.cols[g]) {
                        if (line[col] != '#') { col++; continue; }
                        int runStart = col;
                        while (col < rc.cols[g] && line[col] == '#') col++;
                        r.FillRect(cursorX + runStart * dot, y + row * dot,
                                   (col - runStart) * dot, dot, color);
                    }
                }
            }
            cursorX += rc.advance[g] * dot;
        }
    }
}

void DrawPixelTextCentered(Renderer& r, const std::string& text,
                           float x, float y, float w, float h, float dot, Color color) {
    float textW = PixelTextWidth(text, dot);
    float textH = kGlyphRows * dot;
    DrawPixelText(r, text, x + (w - textW) / 2.0f, y + (h - textH) / 2.0f, dot, color);
}

void DrawPixelTextRight(Renderer& r, const std::string& text, float rightX, float y,
                        float dot, Color color) {
    DrawPixelText(r, text, rightX - PixelTextWidth(text, dot), y, dot, color);
}

