// =====================================================================
// 日本語（カナ）のグリフ  8x8
// =====================================================================
// 英数字が 5x7 なのに対して、カナは 8x8 で描きます。カナは英字より
// 画数が多く、5x7 では「ホ」と「木」の区別すらつかないためです。
// 逆に 8x8 より大きくすると、384x224 の画面には 1 行あたり 40 字ほどしか
// 入らなくなり、項目名と数値を 1 行に並べられなくなります。
//
// 濁点・半濁点は「別の 1 文字」として描きます
// ------------------------------------------
// 「ガ」を 8x8 の枠に濁点まで詰め込むと、点が「カ」の横棒とくっついて
// 何の字か読めなくなります。そこで濁点を独立した文字として、
// 素の字のうしろに続けて描きます（ガ → カ ＋ ゛）。
// ファミコン時代の日本語表示と同じやり方です。文字数は増えますが、
// この大きさでは読めることのほうが大事です。
//
// ひらがなはカタカナで表示します
// ---------------------------
// 8x8 では、ひらがなの曲線（あ・ぬ・め・わ など）を描き分けられません。
// そこでひらがなが来たらカタカナに置き換えて描きます。文字コード上、
// ひらがなとカタカナは 0x60 ずれた同じ並びなので、足すだけで対応します。
// 「なまえ」と入力しても「ナマエ」と出ますが、消えるより読めるほうが
// 良いという判断です。
