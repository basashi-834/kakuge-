// =====================================================================
// platform/SpriteExport.h - 図形描画をスプライトの「型紙」に書き出す
// =====================================================================
// スプライトを差し込むときに一番つまずくのが、
//   ・1 コマの大きさをいくつにすればいいのか
//   ・絵の中で足元をどこに置けばいいのか
//   ・どの姿勢の絵を用意すればいいのか
// の 3 点です。ここを外すと、技を出すたびに絵がずれます。
//
// そこでこのファイルは、今の図形描画をそのままシート画像
// （BMP）と sprites.json に書き出します。できあがったシートを
// お絵かきソフトで開き、コマの上から描き直していけば、
// 位置の合ったスプライトが確実に作れます。
//
//   Kakuge --export-sprites          … 全キャラクターぶん
//   Kakuge --export-sprites ryu      … ryu だけ
//
// ゲーム画面は開かず、書き出したら終了します。
// =====================================================================
#pragma once
#include <string>

namespace kakuge {

// 書き出しを実行する。戻り値はそのまま main の戻り値にできます
//（0 = 成功、1 = 失敗）。characterId が空なら全キャラクターぶん。
int ExportSpriteSheets(const std::string& characterId);

} // namespace kakuge
