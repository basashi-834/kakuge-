// =====================================================================
// platform/Palette.h - 画面全体で使う色の一覧
// =====================================================================
// 色をコードのあちこちに直接書くと、あとで «赤をもう少し暗く» と
// 思ったときに何十か所も直すことになります。ここに名前を付けて
// 集めておけば、1 か所直すだけで画面全体の色が変わります。
//
// このゲームの配色は「明るい下地に、はっきりした赤の差し色」。
// 角を丸めず、影もぼかさない、平面的でくっきりしたデザインです。
// 対戦画面だけは例外で、キャラクターを目立たせるため
// 暗い背景（Arena***）を使います。
// =====================================================================
#pragma once
#include "platform/Renderer.h"

namespace kakuge {

struct Palette {
    // ---- 明るい画面（タイトル・キャラ選択・結果）----
    Color Bg{243, 242, 242};        // 下地
    Color Ink{32, 30, 29};          // 線・枠・本文の文字
    Color Ink70{68, 65, 65};        // やや薄い文字
    Color Ink55{96, 93, 93};        // ラベル用の薄い文字
    Color Ink45{125, 121, 121};     // いちばん薄い文字
    Color Accent{236, 48, 19};      // 差し色の赤
    Color AccentDeep{174, 24, 0};   // 濃い赤（文字用）
    Color OnAccent{255, 255, 255};  // 赤の上に載せる文字
    Color RuleSoft{32, 30, 29, 64}; // 薄い区切り線
    Color EmptyBar{32, 30, 29, 38}; // ゲージの空の部分
    Color PanelBg{255, 255, 255};   // パネルの下地
    Color PanelBg2{236, 236, 234};  // 選択中のパネル
    Color GroundStrip{224, 210, 196};// 地面の帯
    Color White{255, 255, 255};

    // ---- 対戦画面（暗い背景）----
    Color ArenaBg{58, 56, 55};        // 対戦画面の背景
    Color ArenaPanel{40, 38, 37};     // 名前欄などのパネル
    Color ArenaLine{235, 232, 230};   // 暗い背景の上で見える線・文字
    Color ArenaTextDim{235, 232, 230, 200}; // 補助的な文字
};

// どこからでも同じ配色を参照できるようにするための関数。
// static なので、最初に呼ばれたとき 1 回だけ作られます。
inline const Palette& GetPalette() {
    static Palette p;
    return p;
}

} // namespace kakuge
