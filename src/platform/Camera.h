// =====================================================================
// platform/Camera.h - カメラ（横スクロール）と座標変換
// =====================================================================
// ゲーム内部の座標（ワールド座標）は「ステージ中央が X=0、地面が Y=0」。
// 一方、描画に使う座標（画面座標）は「左上が (0,0)、右下が (384,224)」。
// この 2 つを変換するのがカメラの役割です。
//
// このカメラは「拡大縮小しません」
// -----------------------------
// 対戦中の表示倍率は常に 100% 固定です。2 人が近づいても離れても、
// キャラクターの大きさは一切変わりません。カメラは横にスクロール
// するだけです。
//
// なぜ自動ズームをやめたのか
// -----------------------
// 格闘ゲームでは「この距離ならこの技が届く」という間合いの感覚が
// 何より大事です。距離によって表示倍率が変わると、
//   ・技のリーチ
//   ・歩いて詰められる距離
//   ・ジャンプの跳び込み距離
// のすべてが、画面上では毎回違う長さに見えてしまいます。
// 目で覚えた間合いが使えなくなり、腕が上達しません。
//
// そこで倍率は固定し、代わりに
//   ・カメラの横スクロール
//   ・2 人の最大距離の制限（StageConstants::MaxPlayerDistance）
//   ・ステージ端
// の 3 つで 2 人を画面内に収めます。
//
// ズームを使ってよいのは、ラウンド開始・超必殺技・KO などの
// 「演出」の場面だけです（演出が終わったら必ず 100% に戻します）。
//
// デッドゾーン
// ----------
// 2 人の中間点をそのまま追いかけると、少し歩くだけで背景が動いて
// 画面が落ち着きません。そこで画面中央に「この中なら動かさない」
// という帯（デッドゾーン）を設けています。中間点がその帯から
// はみ出したぶんだけカメラが動きます。
// =====================================================================
#pragma once
#include "engine/Constants.h"
#include "platform/Renderer.h"

namespace kakuge {

// ワールド座標の原点が、画面座標のどこに来るか。
constexpr double OriginX = VirtualW / 2.0;      // 画面の横中央（192）
constexpr double OriginY = GameSpec::GroundY;   // 地面の線（上から 200px）

struct GameCamera {
    // 今どのワールド座標を画面中央に映しているか。
    // なめらかに動かすため小数で持ちますが、描画に使うときは
    // 必ず整数に丸めます（DrawCenterX を参照）。
    double CenterX = 0.0;
};

// カメラは 1 つしか無いので、どこからでも同じものを参照します。
GameCamera& GetCamera();

// 描画に使うカメラ位置（整数に丸めたもの）。
//
// なぜ丸めるのか: 小数のままだと、キャラクターや背景が
// 0.5 ピクセルずれた位置に描かれます。ドット絵では、これが
//   ・輪郭がにじむ
//   ・ドットの大きさが場所によって変わる
//   ・止まっているはずの背景が細かく震える
// といった形で目に見えて汚くなります。
// 内部では小数で滑らかに動かし、描く瞬間だけ整数にします。
double CameraDrawX();

// 2 人の位置からカメラの目標を計算し、そこへ少しずつ近づける。
// 対戦中、毎フレーム 1 回だけ呼びます。
void UpdateCamera(double p1x, double p2x, double dt);

// カメラを目標位置に「一瞬で」合わせる。
// 試合開始時に呼び、前の試合のカメラ位置を引きずらないようにします。
void ResetCamera(double p1x, double p2x);

// ---- 座標変換 ----
// 表示倍率が 100% 固定なので、変換は「カメラのぶんだけ横にずらす」
// だけです。掛け算が要りません。
inline double ToScreenX(double worldX) {
    return OriginX + (worldX - CameraDrawX());
}
inline double ToScreenY(double worldY) {
    return OriginY + worldY;
}

} // namespace kakuge
