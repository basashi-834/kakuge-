// =====================================================================
// platform/Font.h - 手描きのドットフォント（英数字 5x7 / カナ 8x8）
// =====================================================================
// なぜ普通のフォントを使わないのか
// -----------------------------
// SDL2 単体では文字を描く機能がありません（SDL_ttf という別の
// ライブラリが必要です）。しかしこのプロジェクトは
// 「使うライブラリは SDL2 だけ」と決めているので使えません。
//
// もっとも、仮に使えたとしても、このゲームには向いていません。
// 内部キャンバスが 384x224 しかないため、普通のフォントで
// 文字を出すと 6-8 ピクセルの高さになり、輪郭をなめらかにする処理
// （アンチエイリアス）のせいで灰色ににじんで読めなくなります。
//
// そこで、1 文字を 5x7 の点の並びとして手で描いたフォントを
// 用意しました。ドット絵のゲームの文字は、たいていこの方式です。
//
// パソコンの日本語フォントを使う
// -------------------------
// 起動時に、パソコンに入っている日本語フォント（メイリオ、MS ゴシック、
// IPA ゴシックなど）を探して読み込みます。見つかれば、日本語は
// そのフォントを 12 ピクセルの白黒に変換して描きます。漢字も
// ひらがなも、そのまま出せます。
//
// 中間色は使わず「点を打つか打たないか」だけに変換するので、
// 拡大してもにじまず、ドット絵の画面になじみます。
// 変換のしくみは core/TrueType.h にあります。
//
// フォントが見つからない環境では、下に書いた内蔵のカナ表示に
// 自動で戻ります（ひらがなはカタカナに置き換わります）。
// data フォルダに font.ttf（または font.ttc）を置けば、
// そちらが最優先で使われます。
//
// 英数字は、フォントが読めても内蔵の 5x7 のままです。
// 画面の配置がすべて 5x7 の幅を前提に組んであるので、ここだけは
// 変えないほうが安全だからです。
//
// 使える文字（内蔵ぶん）
// -------------------
//  - 英大文字 A-Z、数字 0-9、空白、記号 - . : + ( ) , = > < / ! ?  … 5x7
//    小文字は自動的に大文字に変換されます（大文字だけの見た目で統一）。
//  - カタカナ（濁点・半濁点・小書きのカナ・長音・、。・）… 8x8
//  - ひらがな … カタカナに置き換えて表示します
//
// 日本語の扱い（ここが少し変わっています）
// ----------------------------------
// 8x8 という大きさでは、ひらがなの曲線（あ・ぬ・め・わ など）を
// 描き分けられません。かといって字を大きくすると、384x224 の画面に
// 1 行ぶんの項目名と数値が並びません。
// そこで「ひらがなが来たらカタカナで描く」という割り切りをしています。
// 「なまえ」と書いても「ナマエ」と出ます。ファミコン時代の
// 日本語表示と同じで、この大きさでは読めることを優先した結果です。
//
// 濁点つきの字（ガ・パなど）は、素の字と点の 2 文字ぶんの幅を使って
// 「カ ゛」のように描きます。8x8 の枠に点まで詰め込むと、
// 横棒とくっついて何の字か分からなくなるためです。
//
// 漢字は入っていません。渡されても落ちたり豆腐（□）を出したりせず、
// 全角ぶんの空白として扱います。
//
// dot（ドットの大きさ）
// -------------------
// 文字を構成する点 1 個ぶんの大きさ（内部キャンバスのピクセル数）です。
//   dot = 1 … 英数字 5x7 / カナ 8x8（HUD の名前など）
//   dot = 2 … その 2 倍（見出し）
//   dot = 3 … その 3 倍（タイトル）
// 送り幅は英数字が 6 ドット、カナが 9 ドット、濁点・半濁点が 6 ドットです。
// =====================================================================
#pragma once
#include <string>

#include "platform/Renderer.h"

namespace kakuge {

// 日本語フォントの準備。起動時に 1 回だけ呼びます。
//   dataDir … data フォルダの場所。ここに font.ttf / font.ttc があれば
//             それを最優先で使います。
// 読み込めたら true。失敗しても描画は内蔵のカナに戻るだけなので、
// 戻り値を無視しても構いません。
bool InitJapaneseFont(const std::string& dataDir);

// 今どのフォントで日本語を出しているか（画面に出して確認するため）。
// 内蔵のカナを使っている場合は空文字列を返します。
std::string JapaneseFontPath();

// 日本語 1 行ぶんの高さ（dot = 1 のときのピクセル数）。
// 項目を縦に並べるときの行間の目安に使います。
int JapaneseLineHeight();

// 文字列を描いたときの幅を計算する（中央揃えなどの位置決めに使う）。
float PixelTextWidth(const std::string& text, float dot);

// 左上を (x, y) として描く。
void DrawPixelText(Renderer& r, const std::string& text, float x, float y, float dot, Color color);

// 指定した四角形の中央に描く。
void DrawPixelTextCentered(Renderer& r, const std::string& text,
                           float x, float y, float w, float h, float dot, Color color);

// 右端を rightX にそろえて描く（2P 側の表示など）。
void DrawPixelTextRight(Renderer& r, const std::string& text, float rightX, float y,
                        float dot, Color color);

} // namespace kakuge
