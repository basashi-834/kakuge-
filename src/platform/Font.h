// =====================================================================
// platform/Font.h - 手描きのドットフォント（5x7）
// =====================================================================
// なぜ普通のフォントを使わないのか
// -----------------------------
// SDL2 単体では文字を描く機能がありません（SDL_ttf という別の
// ライブラリが必要です）。しかしこのプロジェクトは
// 「使うライブラリは SDL2 だけ」と決めているので使えません。
//
// もっとも、仮に使えたとしても、このゲームには向いていません。
// 内部キャンバスが 384x224 しかないため、普通のフォントで
// 文字を出すと 6-8 ピクセルの高さになり、輪郭をなめらかにする処理
// （アンチエイリアス）のせいで灰色ににじんで読めなくなります。
//
// そこで、1 文字を 5x7 の点の並びとして手で描いたフォントを
// 用意しました。ドット絵のゲームの文字は、たいていこの方式です。
//
// 使える文字
// ---------
// 英大文字 A-Z、数字 0-9、空白、記号 - . : + ( ) , = > / ! ?
// 小文字は自動的に大文字に変換されます（大文字だけの見た目で統一）。
// 日本語などの対応していない文字は「何も描かないが、幅は進める」
// という扱いです。文字化けの四角（豆腐）を出したり、
// 落ちたりしないようにするためです。
//
// dot（ドットの大きさ）
// -------------------
// 文字を構成する点 1 個ぶんの大きさ（内部キャンバスのピクセル数）です。
//   dot = 1 … 5x7 ピクセルの極小文字（HUD の名前など）
//   dot = 2 … 10x14 ピクセル（見出し）
//   dot = 3 … 15x21 ピクセル（タイトル）
// 文字の送り幅は 6 ドット（5 ドット＋1 ドットの隙間）です。
// =====================================================================
#pragma once
#include <string>

#include "platform/Renderer.h"

namespace kakuge {

// 文字列を描いたときの幅を計算する（中央揃えなどの位置決めに使う）。
float PixelTextWidth(const std::string& text, float dot);

// 左上を (x, y) として描く。
void DrawPixelText(Renderer& r, const std::string& text, float x, float y, float dot, Color color);

// 指定した四角形の中央に描く。
void DrawPixelTextCentered(Renderer& r, const std::string& text,
                           float x, float y, float w, float h, float dot, Color color);

// 右端を rightX にそろえて描く（2P 側の表示など）。
void DrawPixelTextRight(Renderer& r, const std::string& text, float rightX, float y,
                        float dot, Color color);

} // namespace kakuge
